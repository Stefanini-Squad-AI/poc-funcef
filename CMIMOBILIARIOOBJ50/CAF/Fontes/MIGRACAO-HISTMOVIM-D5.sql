/* VALORES MOVIMENTADOS */
UPDATE HISTORICOMOVIMENTACAO HM
SET (HM.VALOFI,HM.VALFIS,HM.VALGER) = (SELECT VM.VALOFI,VM.VALFIS,VM.VALGER
                                       FROM VALORMOVIMENTACAO VM
                                       WHERE (HM.IDMOVIMENTACAO = VM.IDMOVIMENTACAO))
WHERE (EXISTS (SELECT HM.IDMOVIMENTACAO
               FROM VALORMOVIMENTACAO VM1
               WHERE (HM.IDMOVIMENTACAO = VM1.IDMOVIMENTACAO)));

/* DEPRECIACAO BEM */
UPDATE HISTORICOMOVIMENTACAO HM
SET (HM.DATAULTDEP) = (SELECT DB.DATAULTDEP
                       FROM DEPRECIACAOBEM DB
                       WHERE (HM.IDMOVIMENTACAO = DB.IDMOVIMENTACAO(+)) )
WHERE (HM.IDTIPOMOVIMENTACAO IN (14,17,15,21))
  AND (EXISTS (SELECT HM.IDMOVIMENTACAO
               FROM DEPRECIACAOBEM DB
               WHERE (HM.IDMOVIMENTACAO = DB.IDMOVIMENTACAO)));

