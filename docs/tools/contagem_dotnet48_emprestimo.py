def rel(p):
    return Path(p).relative_to(TARGET).as_posix()


def inside_target(p):
    try:
        Path(os.path.realpath(p)).relative_to(os.path.realpath(TARGET))
        return True
    except ValueError:
        return False


def walk_target():
    """Lista arquivos da pasta-alvo sem seguir links simbólicos; registra diretórios excluídos."""
    files, excluded_dirs, symlinks = [], [], []
    for dirpath, dirnames, filenames in os.walk(TARGET, followlinks=False):
        keep = []
        for d in sorted(dirnames):
            full = os.path.join(dirpath, d)
            if os.path.islink(full):
                symlinks.append(rel(full))
            elif d.lower() in EXCLUDED_DIRS:
                excluded_dirs.append(rel(full))
            else:
                keep.append(d)
        dirnames[:] = keep
        for f in sorted(filenames):
            full = os.path.join(dirpath, f)
            if os.path.islink(full):
                symlinks.append(rel(full))
            elif inside_target(full):
                files.append(Path(full))
    return files, excluded_dirs, symlinks


def file_ext(p):
    name = p.name.lower()
    if name.startswith(".") and name.count(".") == 1:
        return name
    return p.suffix.lower() or "(sem extensão)"


SLN_PROJECT_RE = re.compile(r'^Project\("\{[^}]+\}"\)\s*=\s*"([^"]+)",\s*"([^"]+\.csproj)"', re.M)


def solution_projects():
    """Projetos .csproj da solução: (dentro da pasta-alvo, fora da pasta-alvo — não lidos)."""
    inside, outside = [], []
    for name, path in SLN_PROJECT_RE.findall(SOLUTION.read_text(encoding="utf-8-sig")):
        full = TARGET / PureWindowsPath(path).as_posix()
        (inside if inside_target(full) and full.is_file() else outside).append((name, PureWindowsPath(path).as_posix()))
    return inside, outside


def project_items(csproj):
    """Itens (Compile/Content/None/TypeScriptCompile) declarados no .csproj, resolvidos como Path."""
    items, outside = set(), []
    root = ET.parse(csproj).getroot()
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        inc = el.get("Include")
        if tag in ("Compile", "Content", "None", "TypeScriptCompile") and inc:
            full = Path(os.path.normpath(csproj.parent / PureWindowsPath(inc).as_posix()))
            if inside_target(full):
                items.add(full)
            else:
                outside.append(inc)
    return items, outside


def vendor_of(path, text):
    key = rel(path)
    if key in VENDOR_PATHS:
        return VENDOR_PATHS[key]
    head = text[:3000]
    for rx, lib in VENDOR_SIGNATURES:
        if rx.search(head):
            return lib
    return None


def is_generated(path, text):
    name = path.name.lower()
    head = "\n".join(text.splitlines()[:15])
    return name.endswith(".designer.cs") or bool(GENERATED_RE.search(head))


def analyze():
    files, excluded_dirs, symlinks = walk_target()
    sln_inside, sln_outside = solution_projects()
    referenced, project_of, outside_refs = set(), {}, []
    for _, path in sln_inside:
        csproj = TARGET / path
        items, outside = project_items(csproj)
        referenced |= items
        outside_refs += [(path, o) for o in outside]
        for it in items:
            project_of.setdefault(it, csproj.stem)
    frameworks = {}
    for csproj in sorted(TARGET.rglob("*.csproj")):
        m = re.search(r"<TargetFrameworkVersion>([^<]+)<", csproj.read_text(encoding="utf-8-sig", errors="replace"))
        frameworks[rel(csproj)] = m.group(1) if m else "?"

    ext_found = Counter(file_ext(f) for f in files)
    counted, uncertain, minified, info = [], [], [], []
    for f in files:
        ext = file_ext(f)
        name = f.name.lower()
        if ext in INFO_EXTS:
            text = decode(f.read_bytes())
            info.append({"path": rel(f), "ext": ext, "lines": count_lines(text, INFO_EXTS[ext])})
            continue
        if ext not in EXTS:
            continue
        if name.endswith(MINIFIED):
            minified.append(rel(f))
            continue
        text = decode(f.read_bytes())
        rec = {"path": rel(f), "ext": ext, "lines": count_lines(text, LANG[ext]),
               "project": project_of.get(Path(os.path.normpath(f)), "—"), "reason": None, "detail": ""}
        if Path(os.path.normpath(f)) not in referenced:
            rec["reason"] = "fora-da-solucao"
            rec["detail"] = orphan_detail(f)
        elif vendor_of(f, text):
            rec["reason"], rec["detail"] = "terceiros", vendor_of(f, text)
        elif is_generated(f, text):
            rec["reason"] = "gerado"
            rec["detail"] = "Designer de página/relatório" if name.endswith(".designer.cs") else "Proxy/artefato <auto-generated>"
        (uncertain if rec["reason"] else counted).append(rec)

    return {
        "files": files, "excluded_dirs": excluded_dirs, "symlinks": symlinks,
        "sln_inside": sln_inside, "sln_outside": sln_outside, "outside_refs": outside_refs,
        "frameworks": frameworks, "ext_found": ext_found, "counted": counted,
        "uncertain": uncertain, "minified": minified, "info": info,
    }


def orphan_detail(f):
    r = rel(f)
    if "/" not in r:
        return "Arquivo avulso na raiz (teste/exemplo de diagnóstico)"
    if r.startswith("FUNCEF.WebEmprestimo.Bibliotecas/FUNCEF.WebEmprestimo.AcessoDados.Objetos/"):
        return "Cópia do projeto AcessoDados.Objetos dentro de Bibliotecas (fora da .sln)"
    if f.name.lower().startswith("old-"):
        return "Versão antiga (prefixo old-)"
    return "Presente em disco, não incluído em nenhum .csproj da solução"


