    w("- **Confirmação:** nenhuma pasta fora de `FUNCEF.WebEmprestimo/` foi lida, analisada ou incluída no total. "
      "O script percorre apenas a pasta-alvo (`os.walk` sem seguir links) e valida que cada arquivo resolvido "
      "está dentro dela. Código .NET 10, Delphi 5 e demais pastas do repositório não foram considerados.\n")
    if a["sln_outside"]:
        w(f"- A `.sln` referencia {len(a['sln_outside'])} projetos **fora** da pasta-alvo; foram registrados e **não** analisados:\n")
        for name, path in a["sln_outside"]:
            w(f"  - `{path}`\n")
    if a["outside_refs"]:
        w(f"- {len(a['outside_refs'])} itens de `.csproj` apontam para fora da pasta-alvo e foram ignorados.\n")
    w("\n")

    w("## 3. Extensões encontradas × incluídas\n\n")
    w("| Extensão | Arquivos encontrados | Incluída? | Observação |\n|---|---:|---|---|\n")
    for ext, n in sorted(a["ext_found"].items(), key=lambda x: (-x[1], x[0])):
        if ext in EXTS:
            inc, obs = "Sim", "Código-fonte (lista autorizada)"
            if ext in (".js", ".css"):
                nmin = sum(1 for m in a["minified"] if m.lower().endswith(ext))
                if nmin:
                    obs += f"; {nmin} minificado(s) excluído(s)"
        elif ext in INFO_EXTS:
            inc, obs = "Não", "Contém código, mas não está na lista autorizada — ver §7"
        else:
            inc, obs = "Não", NON_CODE.get(ext, "não é código-fonte")
        w(f"| `{ext}` | {fmt(n)} | {inc} | {obs} |\n")
    missing = [e for e in EXTS if e not in a["ext_found"]]
    if missing:
        w(f"\nExtensões da lista autorizada **não encontradas** na pasta: {', '.join(f'`{e}`' for e in missing)}.\n")
    w("\n")

    w("## 4. Exclusões aplicadas\n\n")
    w("| Exclusão | Regra | Ocorrências |\n|---|---|---:|\n")
    for d in EXCLUDED_DIRS:
        n = sum(1 for x in a["excluded_dirs"] if x.rsplit("/", 1)[-1].lower() == d)
        w(f"| Diretório `{d}/` | Artefato gerado / dependência | {n} |\n")
    w(f"| Arquivos `*.min.js` / `*.min.css` | Minificados | {len(a['minified'])} |\n")
    w("| Extensões não autorizadas | Configuração, documentação, recursos, imagens, binários etc. (§3) | "
      f"{fmt(sum(n for e, n in a['ext_found'].items() if e not in EXTS))} |\n")
