def fmt(n):
    return f"{n:,}".replace(",", ".")


def totals(recs):
    t = [0, 0, 0, 0]
    for r in recs:
        for k in range(4):
            t[k] += r["lines"][k]
    return t


def by_ext(recs):
    groups = defaultdict(list)
    for r in recs:
        groups[r["ext"]].append(r)
    return groups


