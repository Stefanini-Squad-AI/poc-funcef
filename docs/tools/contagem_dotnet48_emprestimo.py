class Scanner:
    """Percorre o texto marcando, por linha física, se há caractere de código e/ou de comentário."""

    def __init__(self, text):
        self.t, self.i, self.n, self.line = text, 0, len(text), 0
        nlines = text.count("\n") + 1
        self.code = [False] * nlines
        self.comment = [False] * nlines

    def at(self, s, ci=False):
        chunk = self.t[self.i:self.i + len(s)]
        return chunk.lower() == s if ci else chunk == s

    def eat(self, k, kind):
        for c in self.t[self.i:self.i + k]:
            if c == "\n":
                self.line += 1
            elif not c.isspace():
                (self.code if kind == "code" else self.comment)[self.line] = True
        self.i = min(self.i + k, self.n)

    def eat_until(self, closer, kind, stop=None, newline=False):
        """Consome até `closer` inclusive (ou fim da linha/`stop`, sem consumi-los)."""
        while self.i < self.n:
            if stop and self.at(stop, ci=True):
                return
            if newline and self.t[self.i] == "\n":
                return
            if closer and self.at(closer):
                self.eat(len(closer), kind)
                return
            self.eat(1, kind)

    def server_tag(self):
        """Trata <%-- --%> e <% %> embutidos em script/estilo de páginas ASP.NET."""
        if self.at("<%--"):
            self.eat_until("--%>", "comment")
            return True
        if self.at("<%"):
            self.eat_until("%>", "code")
            return True
        return False


REGEX_PREV_CHARS = set("(,=:[!&|?{};+-*%<>~^")
REGEX_PREV_WORDS = {"return", "typeof", "case", "in", "of", "new", "delete", "void", "throw", "else", "do"}


def scan_clike(s, lang, stop=None, server_tags=False):
    """C#, JavaScript e TypeScript."""
    prev_char, prev_word = None, None
    while s.i < s.n:
        if stop and s.at(stop, ci=True):
            return
        if server_tags and s.server_tag():
            prev_char, prev_word = ")", None
            continue
        c = s.t[s.i]
        if c.isspace():
            s.eat(1, "code")
        elif s.at("//"):
            s.eat_until(None, "comment", stop=stop, newline=True)
        elif s.at("/*"):
            s.eat(2, "comment")
            s.eat_until("*/", "comment", stop=stop)
        elif lang == "cs" and (s.at('@"') or s.at('$@"') or s.at('@$"')):
            s.eat(s.t.index('"', s.i) - s.i + 1, "code")
            while s.i < s.n:  # string verbatim: multilinha, "" é escape
                if s.at('""'):
                    s.eat(2, "code")
                elif s.at('"'):
                    s.eat(1, "code")
                    break
                else:
                    s.eat(1, "code")
            prev_char, prev_word = '"', None
        elif c in "\"'" or (lang == "js" and c == "`"):
            s.eat(1, "code")
            while s.i < s.n:
                ch = s.t[s.i]
                if ch == "\\":
                    s.eat(2, "code")
                elif ch == c:
                    s.eat(1, "code")
                    break
                elif ch == "\n" and c != "`":
                    break  # string não terminada: não deixa vazar para as linhas seguintes
                else:
                    s.eat(1, "code")
            prev_char, prev_word = c, None
        elif lang == "js" and c == "/" and (prev_char is None or prev_char in REGEX_PREV_CHARS
                                             or prev_word in REGEX_PREV_WORDS):
            s.eat(1, "code")
            in_class = False
            while s.i < s.n and s.t[s.i] != "\n":
                ch = s.t[s.i]
                if ch == "\\":
                    s.eat(2, "code")
                    continue
                s.eat(1, "code")
                if ch == "[":
                    in_class = True
                elif ch == "]":
                    in_class = False
                elif ch == "/" and not in_class:
                    break
            prev_char, prev_word = "/", None
        elif c.isalnum() or c in "_$":
            j = s.i
            while j < s.n and (s.t[j].isalnum() or s.t[j] in "_$"):
                j += 1
            prev_word = s.t[s.i:j]
            s.eat(j - s.i, "code")
            prev_char = "a"
        else:
            s.eat(1, "code")
            prev_char, prev_word = c, None


def scan_css(s, stop=None, server_tags=False):
    while s.i < s.n:
        if stop and s.at(stop, ci=True):
            return
        if server_tags and s.server_tag():
            continue
        c = s.t[s.i]
        if s.at("/*"):
            s.eat(2, "comment")
            s.eat_until("*/", "comment", stop=stop)
        elif c in "\"'":
            s.eat(1, "code")
            s.eat_until(c, "code", stop=stop, newline=True)
        else:
            s.eat(1, "code")


def scan_sql(s):
    while s.i < s.n:
        c = s.t[s.i]
        if s.at("--"):
            s.eat_until(None, "comment", newline=True)
        elif s.at("/*"):
            s.eat(2, "comment")
            s.eat_until("*/", "comment")
        elif c in "'\"":  # '' e "" dentro da string são reabertura imediata: mesmo efeito
            s.eat(1, "code")
            s.eat_until(c, "code")
        else:
            s.eat(1, "code")


TAG_RE = re.compile(r"<(script|style)(?=[\s>])", re.I)
RUNAT_SERVER_RE = re.compile(r"runat\s*=\s*[\"']?server", re.I)


def scan_markup(s, razor=False):
    while s.i < s.n:
        if s.at("<%--"):
            s.eat_until("--%>", "comment")
        elif s.at("<%"):
            s.eat(2, "code")
            scan_clike(s, "cs", stop="%>")
            s.eat(2, "code")
        elif s.at("<!--[if", ci=True):
            s.eat_until("]>", "code")
        elif s.at("<!--"):
            s.eat_until("-->", "comment")
        elif razor and s.at("@*"):
            s.eat_until("*@", "comment")
        elif s.t[s.i] == "<" and TAG_RE.match(s.t, s.i):
            tag = TAG_RE.match(s.t, s.i).group(1).lower()
            end = s.i
            while end < s.n and s.t[end] != ">":  # ignora o ">" de <%= ... %> nos atributos
                end = s.t.find("%>", end) + 2 if s.t.startswith("<%", end) and "%>" in s.t[end:] else end + 1
            end = min(end + 1, s.n)
            open_tag = s.t[s.i:end]
            s.eat(end - s.i, "code")
            if open_tag.endswith("/>"):
                continue
            if tag == "style":
                scan_css(s, stop="</style", server_tags=True)
            else:
                lang = "cs" if RUNAT_SERVER_RE.search(open_tag) else "js"
                scan_clike(s, lang, stop="</script", server_tags=lang == "js")
        else:
            s.eat(1, "code")


def decode(data):
    for enc in ("utf-8-sig", "cp1252", "latin-1"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            continue


def count_lines(text, lang):
    """Retorna (fisicas, codigo, comentario, vazias)."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    if text.endswith("\n"):
        text = text[:-1]
    if not text:
        return 0, 0, 0, 0
    s = Scanner(text)
    if lang in ("cs", "js"):
        scan_clike(s, lang)
    elif lang == "css":
        scan_css(s)
    elif lang == "sql":
        scan_sql(s)
    else:
        scan_markup(s, razor=lang == "razor")
    physical = len(s.code)
    code = sum(s.code)
    comment = sum(1 for k, m in zip(s.code, s.comment) if m and not k)
    return physical, code, comment, physical - code - comment


