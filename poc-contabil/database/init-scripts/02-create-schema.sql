-- ================================================================
-- TABLA: PARAMCONTAB (Parâmetros Contábeis por Empresa)
-- Migração de uDbParamcontab.pas / uCtrlContab.pas
-- En el legacy: SELECT PACMOEDAOFICIAL, PACMOEDAGERENCIAL, PACMOEDAGEREN1, PACMOEDAGEREN2
--               FROM PARAMCONTAB WHERE IDPESSOA = Sistema.IdEmpresa
-- FCadContasContabMT.pas FormShow (líneas 740-762): usa CtrlContab (TCtrlContab)
-- que lee de PARAMCONTAB, NO de PARAMGLOBAL.
-- ================================================================

CREATE TABLE CM.PARAMCONTAB (
    IDPESSOA NUMBER(10) NOT NULL,
    -- Configuração de Moedas (prefixo PAC = Parâmetros Contábeis)
    -- 0 = desabilita combo de conversão correspondente
    PACMOEDAOFICIAL NUMBER(10) DEFAULT 0 NOT NULL,
    PACMOEDAGERENCIAL NUMBER(10) DEFAULT 0 NOT NULL,
    PACMOEDAGEREN1 NUMBER(10) DEFAULT 0 NOT NULL,
    PACMOEDAGEREN2 NUMBER(10) DEFAULT 0 NOT NULL,
    -- Contadores de PLAREDUZ por grupo (legacy: uDbParamcontab.pas)
    -- Próximo PLAREDUZ = PACREDUZ{GRUPO} + 1
    -- Atualizado após cada nova conta criada (uCtrlPlanoConta.pas linhas 367-375)
    PACREDUZA NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZP NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZR NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZD NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZC NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZE NUMBER(10) DEFAULT 0 NOT NULL,
    PACREDUZO NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PARAMCONTAB PRIMARY KEY (IDPESSOA)
);

COMMENT ON TABLE CM.PARAMCONTAB IS 'Parâmetros contábeis por empresa (legacy: PARAMCONTAB)';
COMMENT ON COLUMN CM.PARAMCONTAB.IDPESSOA IS 'ID da empresa/pessoa (FK PESSOA)';
COMMENT ON COLUMN CM.PARAMCONTAB.PACMOEDAOFICIAL IS 'ID da Moeda Oficial (0=desabilita combo dbcmbTipOfi)';
COMMENT ON COLUMN CM.PARAMCONTAB.PACMOEDAGERENCIAL IS 'ID da Moeda Gerencial 1 (0=desabilita combo dbcmbTipGer)';
COMMENT ON COLUMN CM.PARAMCONTAB.PACMOEDAGEREN1 IS 'ID da Moeda Gerencial 2 (0=desabilita combo dbcmbTipGer2)';
COMMENT ON COLUMN CM.PARAMCONTAB.PACMOEDAGEREN2 IS 'ID da Moeda Gerencial 3 (0=desabilita combo dbcmbTipGer3)';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZA IS 'Último PLAREDUZ usado grupo A (Ativo). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZP IS 'Último PLAREDUZ usado grupo P (Passivo). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZR IS 'Último PLAREDUZ usado grupo R (Receita). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZD IS 'Último PLAREDUZ usado grupo D (Despesa). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZC IS 'Último PLAREDUZ usado grupo C (Custo). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZE IS 'Último PLAREDUZ usado grupo E (Estatística). Próximo = +1';
COMMENT ON COLUMN CM.PARAMCONTAB.PACREDUZO IS 'Último PLAREDUZ usado grupo O (Outros). Próximo = +1';

-- Seed: 2 empresas
-- Empresa 1: Moeda Oficial=1, Moeda Gerencial 1=2 (combos habilitados para esas moedas)
-- PACREDUZ* inicializados com o maior PLAREDUZ existente por grupo no seed data
-- Convenção de faixas (unicidade PLAREDUZ é por PLANO, não por GRUPO):
--   A=1xxxx, P=2xxxx, S=3xxxx, R=4xxxx, D=5xxxx, C=6xxxx, E=7xxxx, O=8xxxx
-- Grupos sem contas (C, E, O) inicializados na base da faixa para evitar conflitos
