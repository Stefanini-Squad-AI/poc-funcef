PROMPT === CONTASXCC: FK validation ===
SELECT C.IDCONTACC, C.PLANO, C.PLACONTA, C.CODCENTROCUSTO, C.IDEMPRESA,
       (SELECT COUNT(*) FROM PLANOCONTA P WHERE P.PLANO = C.PLANO AND P.PLACONTA = C.PLACONTA) AS IN_PLANOCONTA,
       (SELECT COUNT(*) FROM CENTCUST CC WHERE CC.IDPESSOA = C.IDEMPRESA AND CC.CODCENTROCUSTO = C.CODCENTROCUSTO) AS IN_CENTCUST
FROM CONTASXCC C
ORDER BY C.PLANO, C.PLACONTA;

