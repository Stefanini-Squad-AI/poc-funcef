SET PLAREDUZ = 11
WHERE PLANO = 1 AND PLACONTA = '1.1' AND PLAREDUZ = 0;

PROMPT === Step 3: Initialize PACREDUZ* with max PLAREDUZ per group ===

-- Empresa 1: Initialize with max PLAREDUZ per group
-- Convenção de faixas (unicidade PLAREDUZ é por PLANO, não por GRUPO):
--   A=1xxxx, P=2xxxx, S=3xxxx, R=4xxxx, D=5xxxx, C=6xxxx, E=7xxxx, O=8xxxx
-- Grupos sem contas (C, E, O) inicializados na base da faixa (NVL fallback)
-- para evitar que PLAREDUZ gerado colida com contas de outros grupos
UPDATE CM.PARAMCONTAB SET
  PACREDUZA = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'A'), 0),
  PACREDUZP = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'P'), 0),
  PACREDUZR = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'R'), 0),
  PACREDUZD = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'D'), 0),
  PACREDUZC = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'C'), 60000),
  PACREDUZE = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'E'), 70000),
  PACREDUZO = NVL((SELECT MAX(PLAREDUZ) FROM CM.PLANOCONTA WHERE PLANO = 1 AND PLAGRUPO = 'O'), 80000)
WHERE IDPESSOA = 1;

PROMPT === Step 4: Recreate trigger TRG_VAL_PLANOCONTA ===

CREATE OR REPLACE TRIGGER CM.TRG_VAL_PLANOCONTA
FOR INSERT OR UPDATE ON CM.PLANOCONTA
COMPOUND TRIGGER

    TYPE t_reduz_rec IS RECORD (
        plano    CM.PLANOCONTA.PLANO%TYPE,
        placonta CM.PLANOCONTA.PLACONTA%TYPE,
        plareduz CM.PLANOCONTA.PLAREDUZ%TYPE
    );
    TYPE t_reduz_tbl IS TABLE OF t_reduz_rec;

    v_reduz_a_validar  t_reduz_tbl := t_reduz_tbl();

    BEFORE EACH ROW IS
    BEGIN
        IF :NEW.PLASUMARIZA = 'S' THEN
            :NEW.PLAALTERA := 'N';
        END IF;

        :NEW.PLAINATIVA  := NVL(:NEW.PLAINATIVA, 'N');
        :NEW.PLASUMARIZA := NVL(:NEW.PLASUMARIZA, 'N');
        :NEW.PLACCUST    := NVL(:NEW.PLACCUST, 'N');
        :NEW.PLACONCILIA := NVL(:NEW.PLACONCILIA, 'N');
        :NEW.PLARATEIOAP := NVL(:NEW.PLARATEIOAP, 'N');
        :NEW.PLAMUTACOES := NVL(:NEW.PLAMUTACOES, 'N');
        :NEW.PLABLOQUE   := NVL(:NEW.PLABLOQUE, 'N');

        -- Skip validacion cuando PLAREDUZ = 0 (auto-generado por la aplicacion)
        IF (:NEW.PLAREDUZ != 0) AND (INSERTING OR (:NEW.PLAREDUZ != NVL(:OLD.PLAREDUZ, -1))) THEN
            v_reduz_a_validar.EXTEND;
            v_reduz_a_validar(v_reduz_a_validar.LAST) :=
                t_reduz_rec(:NEW.PLANO, :NEW.PLACONTA, :NEW.PLAREDUZ);
        END IF;
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        v_existe NUMBER;
    BEGIN
        FOR i IN 1 .. v_reduz_a_validar.COUNT LOOP
            SELECT COUNT(*)
            INTO v_existe
            FROM CM.PLANOCONTA
            WHERE PLANO    = v_reduz_a_validar(i).plano
              AND PLAREDUZ = v_reduz_a_validar(i).plareduz
              AND PLACONTA != v_reduz_a_validar(i).placonta;

            IF v_existe > 0 THEN
                RAISE_APPLICATION_ERROR(-20001,
                    'Cuenta reducida ' || v_reduz_a_validar(i).plareduz ||
                    ' ya existe en el plan ' || v_reduz_a_validar(i).plano);
            END IF;
        END LOOP;
    END AFTER STATEMENT;

END TRG_VAL_PLANOCONTA;
/

COMMIT;

PROMPT === Verification ===

-- Check no more PLAREDUZ=0
SELECT 'PLAREDUZ=0 count: ' || COUNT(*) AS result
FROM CM.PLANOCONTA WHERE PLAREDUZ = 0;

