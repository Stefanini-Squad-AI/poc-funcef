CREATE OR REPLACE TRIGGER CM.TUDLOGALT_PARAM_ETL_ARQUIVODET
BEFORE UPDATE OF                                 
   IDPARAMETLARQ
   ,IDPARAMETL
   ,IDSEQSESSAO
   ,ORDEM
   ,NOMESESSAO
   ,BLOCO
OR DELETE ON PARAM_ETL_ARQUIVODET
FOR EACH ROW                          
DECLARE                               
  vTipoOperacao CHAR(1);              
BEGIN                                 
  IF deleting THEN                    
     vTipoOperacao := 'D';          
  END IF;                             
  IF updating THEN                    
     vTipoOperacao := 'A';          
  END IF;                             
  IF (:NEW.IDPARAMETLARQ <> :OLD.IDPARAMETLARQ) OR
  (:NEW.IDPARAMETLARQ IS NULL AND :OLD.IDPARAMETLARQ IS NOT NULL) OR 
  (:NEW.IDPARAMETLARQ IS NOT NULL AND :OLD.IDPARAMETLARQ IS NULL)    
  OR (:NEW.IDPARAMETL <> :OLD.IDPARAMETL) OR
  (:NEW.IDPARAMETL IS NULL AND :OLD.IDPARAMETL IS NOT NULL) OR 
  (:NEW.IDPARAMETL IS NOT NULL AND :OLD.IDPARAMETL IS NULL)    
  OR (:NEW.IDSEQSESSAO <> :OLD.IDSEQSESSAO) OR
  (:NEW.IDSEQSESSAO IS NULL AND :OLD.IDSEQSESSAO IS NOT NULL) OR 
  (:NEW.IDSEQSESSAO IS NOT NULL AND :OLD.IDSEQSESSAO IS NULL)    
  OR (:NEW.ORDEM <> :OLD.ORDEM) OR
  (:NEW.ORDEM IS NULL AND :OLD.ORDEM IS NOT NULL) OR 
  (:NEW.ORDEM IS NOT NULL AND :OLD.ORDEM IS NULL)    
  OR (:NEW.NOMESESSAO <> :OLD.NOMESESSAO) OR
  (:NEW.NOMESESSAO IS NULL AND :OLD.NOMESESSAO IS NOT NULL) OR 
  (:NEW.NOMESESSAO IS NOT NULL AND :OLD.NOMESESSAO IS NULL)    
  OR (:NEW.BLOCO <> :OLD.BLOCO) OR
  (:NEW.BLOCO IS NULL AND :OLD.BLOCO IS NOT NULL) OR 
  (:NEW.BLOCO IS NOT NULL AND :OLD.BLOCO IS NULL)    
  THEN                                
   INSERT INTO LOGPLANUS.LOG_PLANUS_PARAM_ETL_ARQUIVODET
    (IDLOGPARAM_ETL_ARQDET,
     IDPARAMETLARQ,
     IDPARAMETL,
     IDSEQSESSAO,
     ORDEM,
     NOMESESSAO,
     BLOCO,
     TRGDTINCLUSAO,
     TRGUSERINCLUSAO,
     ROWIDORIGEM,      
     Operacao,         
     TRGDTALTERACAO,   
     TRGUSERALTERACAO  
    ) VALUES (         
     LOGPLANUS.SEQLOGPLANUS_PARAM_ETL_ARQUIVODET.NEXTVAL, 
     :OLD.IDPARAMETLARQ,
     :OLD.IDPARAMETL,
     :OLD.IDSEQSESSAO,
     :OLD.ORDEM,
     :OLD.NOMESESSAO,
     :OLD.BLOCO,
     :OLD.TRGDTINCLUSAO,
     :OLD.TRGUSERINCLUSAO,
     :OLD.ROWID,     
     vTipoOperacao,  
     SYSDATE,        
     USER            
    );               
  END IF;            
END;                 
