CREATE OR REPLACE TRIGGER CM.TUDLOGALT_PARAM_ETL_ARQUIVO
BEFORE UPDATE OF                                 
   IDPARAMETLARQ
   ,IDPARAMETL
   ,ORDEM
   ,FLGUSAPREFIXO
   ,NOMEETLARQUIVO
OR DELETE ON PARAM_ETL_ARQUIVO
FOR EACH ROW                          
DECLARE                               
  vTipoOperacao CHAR(1);              
BEGIN                                 
  IF deleting THEN                    
     vTipoOperacao := 'D';          
  END IF;                             
  IF updating THEN                    
     vTipoOperacao := 'A';          
  END IF;                             
  IF (:NEW.IDPARAMETLARQ <> :OLD.IDPARAMETLARQ) OR
  (:NEW.IDPARAMETLARQ IS NULL AND :OLD.IDPARAMETLARQ IS NOT NULL) OR 
  (:NEW.IDPARAMETLARQ IS NOT NULL AND :OLD.IDPARAMETLARQ IS NULL)    
  OR (:NEW.IDPARAMETL <> :OLD.IDPARAMETL) OR
  (:NEW.IDPARAMETL IS NULL AND :OLD.IDPARAMETL IS NOT NULL) OR 
  (:NEW.IDPARAMETL IS NOT NULL AND :OLD.IDPARAMETL IS NULL)    
  OR (:NEW.ORDEM <> :OLD.ORDEM) OR
  (:NEW.ORDEM IS NULL AND :OLD.ORDEM IS NOT NULL) OR 
  (:NEW.ORDEM IS NOT NULL AND :OLD.ORDEM IS NULL)    
  OR (:NEW.FLGUSAPREFIXO <> :OLD.FLGUSAPREFIXO) OR
  (:NEW.FLGUSAPREFIXO IS NULL AND :OLD.FLGUSAPREFIXO IS NOT NULL) OR 
  (:NEW.FLGUSAPREFIXO IS NOT NULL AND :OLD.FLGUSAPREFIXO IS NULL)    
  OR (:NEW.NOMEETLARQUIVO <> :OLD.NOMEETLARQUIVO) OR
  (:NEW.NOMEETLARQUIVO IS NULL AND :OLD.NOMEETLARQUIVO IS NOT NULL) OR 
  (:NEW.NOMEETLARQUIVO IS NOT NULL AND :OLD.NOMEETLARQUIVO IS NULL)    
  THEN                                
   INSERT INTO LOGPLANUS.LOG_PLANUS_PARAM_ETL_ARQUIVO
    (IDLOGPARAM_ETL_ARQUIVO,
     IDPARAMETLARQ,
     IDPARAMETL,
     ORDEM,
     FLGUSAPREFIXO,
     NOMEETLARQUIVO,
     TRGDTINCLUSAO,
     TRGUSERINCLUSAO,
     ROWIDORIGEM,      
     Operacao,         
     TRGDTALTERACAO,   
     TRGUSERALTERACAO  
    ) VALUES (         
     LOGPLANUS.SEQLOGPLANUS_PARAM_ETL_ARQUIVO.NEXTVAL, 
     :OLD.IDPARAMETLARQ,
     :OLD.IDPARAMETL,
     :OLD.ORDEM,
     :OLD.FLGUSAPREFIXO,
     :OLD.NOMEETLARQUIVO,
     :OLD.TRGDTINCLUSAO,
     :OLD.TRGUSERINCLUSAO,
     :OLD.ROWID,     
     vTipoOperacao,  
     SYSDATE,        
     USER            
    );               
  END IF;            
END;                 
