--CRIAÇÃO DA TRIGGER DA TABELA DE LOG.           
CREATE OR REPLACE TRIGGER CM.TUDLOGALT_DEPARAEXTERNO
BEFORE UPDATE OF                                 
   IDDEPARAEXTERNO
   ,ATRIBUTO
   ,VLRCM
   ,VLREXTERNO
   ,FLGORIGEM
   ,TABELAORIGEM
   ,CAMPOFILTROORIGEM
   ,FLGUSACRITPO
   ,FLGAPLICACRITPO
OR DELETE ON DEPARAEXTERNO
FOR EACH ROW                          
DECLARE                               
  vTipoOperacao CHAR(1);              
BEGIN                                 
  IF deleting THEN                    
     vTipoOperacao := 'D';          
  END IF;                             
  IF updating THEN                    
     vTipoOperacao := 'A';          
  END IF;                             
  IF (:NEW.IDDEPARAEXTERNO <> :OLD.IDDEPARAEXTERNO) OR
  (:NEW.IDDEPARAEXTERNO IS NULL AND :OLD.IDDEPARAEXTERNO IS NOT NULL) OR 
  (:NEW.IDDEPARAEXTERNO IS NOT NULL AND :OLD.IDDEPARAEXTERNO IS NULL)    
  OR (:NEW.ATRIBUTO <> :OLD.ATRIBUTO) OR
  (:NEW.ATRIBUTO IS NULL AND :OLD.ATRIBUTO IS NOT NULL) OR 
  (:NEW.ATRIBUTO IS NOT NULL AND :OLD.ATRIBUTO IS NULL)    
  OR (:NEW.VLRCM <> :OLD.VLRCM) OR
  (:NEW.VLRCM IS NULL AND :OLD.VLRCM IS NOT NULL) OR 
  (:NEW.VLRCM IS NOT NULL AND :OLD.VLRCM IS NULL)    
  OR (:NEW.VLREXTERNO <> :OLD.VLREXTERNO) OR
  (:NEW.VLREXTERNO IS NULL AND :OLD.VLREXTERNO IS NOT NULL) OR 
  (:NEW.VLREXTERNO IS NOT NULL AND :OLD.VLREXTERNO IS NULL)    
  OR (:NEW.FLGORIGEM <> :OLD.FLGORIGEM) OR
  (:NEW.FLGORIGEM IS NULL AND :OLD.FLGORIGEM IS NOT NULL) OR 
  (:NEW.FLGORIGEM IS NOT NULL AND :OLD.FLGORIGEM IS NULL)    
  OR (:NEW.TABELAORIGEM <> :OLD.TABELAORIGEM) OR
  (:NEW.TABELAORIGEM IS NULL AND :OLD.TABELAORIGEM IS NOT NULL) OR 
  (:NEW.TABELAORIGEM IS NOT NULL AND :OLD.TABELAORIGEM IS NULL)    
  OR (:NEW.CAMPOFILTROORIGEM <> :OLD.CAMPOFILTROORIGEM) OR
  (:NEW.CAMPOFILTROORIGEM IS NULL AND :OLD.CAMPOFILTROORIGEM IS NOT NULL) OR 
  (:NEW.CAMPOFILTROORIGEM IS NOT NULL AND :OLD.CAMPOFILTROORIGEM IS NULL)    
  OR (:NEW.FLGUSACRITPO <> :OLD.FLGUSACRITPO) OR
  (:NEW.FLGUSACRITPO IS NULL AND :OLD.FLGUSACRITPO IS NOT NULL) OR 
  (:NEW.FLGUSACRITPO IS NOT NULL AND :OLD.FLGUSACRITPO IS NULL)    
  OR (:NEW.FLGAPLICACRITPO <> :OLD.FLGAPLICACRITPO) OR
  (:NEW.FLGAPLICACRITPO IS NULL AND :OLD.FLGAPLICACRITPO IS NOT NULL) OR 
  (:NEW.FLGAPLICACRITPO IS NOT NULL AND :OLD.FLGAPLICACRITPO IS NULL)    
  THEN                                
   INSERT INTO LOGPLANUS.LOG_PLANUS_DEPARAEXTERNO
    (IDLOGDEPARAEXTERNO,
     IDDEPARAEXTERNO,
     ATRIBUTO,
     VLRCM,
     VLREXTERNO,
     TRGDTINCLUSAO,
     TRGUSERINCLUSAO,
     FLGORIGEM,
     TABELAORIGEM,
     CAMPOFILTROORIGEM,
     FLGUSACRITPO,
     FLGAPLICACRITPO,
     ROWIDORIGEM,      
     Operacao,         
     TRGDTALTERACAO,   
     TRGUSERALTERACAO  
    ) VALUES (         
     LOGPLANUS.SEQLOGPLANUS_DEPARAEXTERNO.NEXTVAL, 
     :OLD.IDDEPARAEXTERNO,
     :OLD.ATRIBUTO,
     :OLD.VLRCM,
     :OLD.VLREXTERNO,
     :OLD.TRGDTINCLUSAO,
     :OLD.TRGUSERINCLUSAO,
     :OLD.FLGORIGEM,
     :OLD.TABELAORIGEM,
     :OLD.CAMPOFILTROORIGEM,
     :OLD.FLGUSACRITPO,
     :OLD.FLGAPLICACRITPO,
     :OLD.ROWID,     
     vTipoOperacao,  
     SYSDATE,        
     USER            
    );               
  END IF;            
END;                 
