	IDLOTEIMPORTA NUMBER NOT NULL,  
	NOMEARQUIVO VARCHAR2(100),
	DATAIMPORTA DATE,
	QTDEITENS NUMBER,
	QTDEIMPORTA NUMBER,
	HASHARQUIVO VARCHAR2(60),
	TRGDTINCLUSAO DATE DEFAULT SYSDATE,
	TRGUSERINCLUSAO VARCHAR(30) DEFAULT USER
