CREATE OR REPLACE TRIGGER CM.TUDLOGALT_HSTARQUIVOALTBENEF 
BEFORE UPDATE OF 
IDLOTEIMPORTA,
NOMEARQUIVO,
DATAIMPORTA,
QTDEITENS,
QTDEIMPORTA,
HASHARQUIVO,
TRGDTINCLUSAO,
TRGUSERINCLUSAO
OR DELETE ON HSTARQUIVOALTBENEF
FOR EACH ROW
DECLARE
vTipoOperacao CHAR(1);
BEGIN
IF deleting THEN
 vTipoOperacao := 'D';
 END IF;
 IF updating THEN
  vTipoOperacao := 'A';
 END IF;
IF  (:NEW.IDLOTEIMPORTA <> :OLD.IDLOTEIMPORTA) OR
    (:NEW.IDLOTEIMPORTA IS NULL AND :OLD.IDLOTEIMPORTA IS NOT NULL) OR
    (:NEW.IDLOTEIMPORTA IS NOT NULL AND :OLD.IDLOTEIMPORTA IS NULL)
 OR (:NEW.NOMEARQUIVO <> :OLD.NOMEARQUIVO) OR
    (:NEW.NOMEARQUIVO IS NULL AND :OLD.NOMEARQUIVO IS NOT NULL) OR
    (:NEW.NOMEARQUIVO IS NOT NULL AND :OLD.NOMEARQUIVO IS NULL)
 OR (:NEW.DATAIMPORTA <> :OLD.DATAIMPORTA) OR
    (:NEW.DATAIMPORTA IS NULL AND :OLD.DATAIMPORTA IS NOT NULL) OR
    (:NEW.DATAIMPORTA IS NOT NULL AND :OLD.DATAIMPORTA IS NULL)
 OR (:NEW.QTDEITENS <> :OLD.QTDEITENS) OR
    (:NEW.QTDEITENS IS NULL AND :OLD.QTDEITENS IS NOT NULL) OR
    (:NEW.QTDEITENS IS NOT NULL AND :OLD.QTDEITENS IS NULL)
 OR (:NEW.QTDEIMPORTA <> :OLD.QTDEIMPORTA) OR
    (:NEW.QTDEIMPORTA IS NULL AND :OLD.QTDEIMPORTA IS NOT NULL) OR
    (:NEW.QTDEIMPORTA IS NOT NULL AND :OLD.QTDEIMPORTA IS NULL)
 OR (:NEW.HASHARQUIVO <> :OLD.HASHARQUIVO) OR
    (:NEW.HASHARQUIVO IS NULL AND :OLD.HASHARQUIVO IS NOT NULL) OR
    (:NEW.HASHARQUIVO IS NOT NULL AND :OLD.HASHARQUIVO IS NULL)
 OR (:NEW.TRGDTINCLUSAO <> :OLD.TRGDTINCLUSAO) OR
    (:NEW.TRGDTINCLUSAO IS NULL AND :OLD.TRGDTINCLUSAO IS NOT NULL) OR
    (:NEW.TRGDTINCLUSAO IS NOT NULL AND :OLD.TRGDTINCLUSAO IS NULL)
 OR (:NEW.TRGUSERINCLUSAO <> :OLD.TRGUSERINCLUSAO) OR
    (:NEW.TRGUSERINCLUSAO IS NULL AND :OLD.TRGUSERINCLUSAO IS NOT NULL) OR
    (:NEW.TRGUSERINCLUSAO IS NOT NULL AND :OLD.TRGUSERINCLUSAO IS NULL)
THEN
INSERT INTO LOGPLANUS.LOG_PLANUS_HSTARQUIVOALTBENEF (
IDLOGHSTARQUIVOALTBENEF,
IDLOTEIMPORTA,
NOMEARQUIVO,
DATAIMPORTA,
QTDEITENS,
QTDEIMPORTA,
HASHARQUIVO,
TRGDTINCLUSAO,
TRGUSERINCLUSAO,
ROWIDORIGEM, 
OPERACAO,
TRGDTALTERACAO,
TRGUSERALTERACAO
)
VALUES (
LOGPLANUS.SEQLOGPLANUS_HSTARQUIVOALTBENEF.NEXTVAL,
:OLD.IDLOTEIMPORTA,
:OLD.NOMEARQUIVO,
:OLD.DATAIMPORTA,
:OLD.QTDEITENS,
:OLD.QTDEIMPORTA,
:OLD.HASHARQUIVO,
:OLD.TRGDTINCLUSAO,
:OLD.TRGUSERINCLUSAO,
:old.rowid, 
vTipoOperacao,
sysdate,
user
);
END IF;
END;