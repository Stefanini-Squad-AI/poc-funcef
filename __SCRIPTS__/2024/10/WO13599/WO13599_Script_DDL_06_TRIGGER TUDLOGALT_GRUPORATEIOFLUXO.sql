CREATE OR REPLACE TRIGGER CM.TUDLOGALT_GRUPORATEIOFLUXO
BEFORE UPDATE OF
IDGRUPORATEIOFLUXO
,GRRFDESCRICAO
,TRGDTINCLUSAO
,TRGUSERINCLUSAO,
TIPORATEIO
OR DELETE ON GRUPORATEIOFLUXO
FOR EACH ROW
DECLARE
vTipoOperacao CHAR(1);
BEGIN
IF deleting THEN
vTipoOperacao := 'D';
END IF;
IF updating THEN
vTipoOperacao := 'A';
END IF;
IF  (:NEW.IDGRUPORATEIOFLUXO <> :OLD.IDGRUPORATEIOFLUXO) OR
(:NEW.IDGRUPORATEIOFLUXO IS NULL AND :OLD.IDGRUPORATEIOFLUXO IS NOT NULL) OR
(:NEW.IDGRUPORATEIOFLUXO IS NOT NULL AND :OLD.IDGRUPORATEIOFLUXO IS NULL)
OR (:NEW.GRRFDESCRICAO <> :OLD.GRRFDESCRICAO) OR
(:NEW.GRRFDESCRICAO IS NULL AND :OLD.GRRFDESCRICAO IS NOT NULL) OR
(:NEW.GRRFDESCRICAO IS NOT NULL AND :OLD.GRRFDESCRICAO IS NULL)
OR (:NEW.TRGDTINCLUSAO <> :OLD.TRGDTINCLUSAO) OR
(:NEW.TRGDTINCLUSAO IS NULL AND :OLD.TRGDTINCLUSAO IS NOT NULL) OR
(:NEW.TRGDTINCLUSAO IS NOT NULL AND :OLD.TRGDTINCLUSAO IS NULL)
OR (:NEW.TRGUSERINCLUSAO <> :OLD.TRGUSERINCLUSAO) OR
(:NEW.TRGUSERINCLUSAO IS NULL AND :OLD.TRGUSERINCLUSAO IS NOT NULL) OR
(:NEW.TRGUSERINCLUSAO IS NOT NULL AND :OLD.TRGUSERINCLUSAO IS NULL)
OR (:NEW.TIPORATEIO <> :OLD.TIPORATEIO) OR
(:NEW.TIPORATEIO IS NULL AND :OLD.TIPORATEIO IS NOT NULL) OR
(:NEW.TIPORATEIO IS NOT NULL AND :OLD.TIPORATEIO IS NULL)

THEN
INSERT INTO LOGPLANUS.LOG_PLANUS_GRUPORATEIOFLUXO (IDLOGGRUPORATEIOFLUXO,
IDGRUPORATEIOFLUXO,
GRRFDESCRICAO,
TRGDTINCLUSAO,
TRGUSERINCLUSAO,
ROWIDORIGEM,
Operacao,
TRGDTALTERACAO,
TRGUSERALTERACAO,
TIPORATEIO
)
VALUES (LOGPLANUS.SEQLOGPLANUS_GRUPORATEIOFLUXO.NEXTVAL,
:OLD.IDGRUPORATEIOFLUXO,
:OLD.GRRFDESCRICAO,
:OLD.TRGDTINCLUSAO,
:OLD.TRGUSERINCLUSAO,
:OLD.ROWID,
vTipoOperacao,
SYSDATE,
USER,
:OLD.TIPORATEIO
);
END IF;
END;
