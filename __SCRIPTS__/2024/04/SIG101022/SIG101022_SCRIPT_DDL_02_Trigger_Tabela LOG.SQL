CREATE OR REPLACE TRIGGER "CM"."TUDLOGALT_ITEMEMPTMO" 
BEFORE UPDATE OF
IDITEMEMPTMO
,ITEDESCRICAO
,FLGABATENEGATIVO
,TRGDTINCLUSAO
,TRGUSERINCLUSAO
OR DELETE ON ITEMEMPTMO
FOR EACH ROW
DECLARE
vTipoOperacao CHAR(1);
BEGIN
IF deleting THEN
vTipoOperacao := 'D';
END IF;
IF updating THEN
vTipoOperacao := 'A';
END IF;
IF  (:NEW.IDITEMEMPTMO <> :OLD.IDITEMEMPTMO) OR
(:NEW.IDITEMEMPTMO IS NULL AND :OLD.IDITEMEMPTMO IS NOT NULL) OR
(:NEW.IDITEMEMPTMO IS NOT NULL AND :OLD.IDITEMEMPTMO IS NULL)
OR (:NEW.ITEDESCRICAO <> :OLD.ITEDESCRICAO) OR
(:NEW.ITEDESCRICAO IS NULL AND :OLD.ITEDESCRICAO IS NOT NULL) OR
(:NEW.ITEDESCRICAO IS NOT NULL AND :OLD.ITEDESCRICAO IS NULL)
OR (:NEW.TRGDTINCLUSAO <> :OLD.TRGDTINCLUSAO) OR
(:NEW.TRGDTINCLUSAO IS NULL AND :OLD.TRGDTINCLUSAO IS NOT NULL) OR
(:NEW.TRGDTINCLUSAO IS NOT NULL AND :OLD.TRGDTINCLUSAO IS NULL)
OR (:NEW.TRGUSERINCLUSAO <> :OLD.TRGUSERINCLUSAO) OR
(:NEW.TRGUSERINCLUSAO IS NULL AND :OLD.TRGUSERINCLUSAO IS NOT NULL) OR
(:NEW.TRGUSERINCLUSAO IS NOT NULL AND :OLD.TRGUSERINCLUSAO IS NULL)
OR (:NEW.FLGABATENEGATIVO <> :OLD.FLGABATENEGATIVO) OR
(:NEW.FLGABATENEGATIVO IS NULL AND :OLD.FLGABATENEGATIVO IS NOT NULL) OR
(:NEW.FLGABATENEGATIVO IS NOT NULL AND :OLD.FLGABATENEGATIVO IS NULL)
THEN
INSERT INTO LOGPLANUS.LOG_PLANUS_ITEMEMPTMO (IDLOGITEMEMPTMO,
IDITEMEMPTMO,
ITEDESCRICAO,
TRGDTINCLUSAO,
TRGUSERINCLUSAO,
FLGABATENEGATIVO,
ROWIDORIGEM,
Operacao,
TRGDTALTERACAO,
TRGUSERALTERACAO
)
VALUES (LOGPLANUS.SEQLOGPLANUS_ITEMEMPTMO.NEXTVAL,
:OLD.IDITEMEMPTMO,
:OLD.ITEDESCRICAO,
:OLD.TRGDTINCLUSAO,
:OLD.TRGUSERINCLUSAO,
:OLD.FLGABATENEGATIVO,
:OLD.ROWID,
vTipoOperacao,
SYSDATE,
USER
);
END IF;
END; 
  
  