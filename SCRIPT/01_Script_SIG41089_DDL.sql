CREATE OR REPLACE PROCEDURE cm.SP_FB_GERALISTAPREVIA(MESPROCESSAMENTO IN VARCHAR2,
                                                          LISTAUSR         IN VARCHAR2) IS

  V_MES   VARCHAR2(7) := MESPROCESSAMENTO; -- MÊS DE PAGAMENTO DA FOLHA DE BENEFÍCIOS
  V_MES13 VARCHAR2(7) := SUBSTR(MESPROCESSAMENTO, 1, 5) || 13;

  V_QTDPROCESSOS  NUMBER := 0; -- QUANTIDADE DE EXECUÇÕES (PESSOAS) SIMULTÂNEAS DA PRÉVIA
  V_QTDMATRICULAS NUMBER := 0; -- TOTAL DE MATRÍCULAS DE TITULARES PARA PAROCESSAMENTO NO MÊS
  V_LISTA         NUMBER := NULL;
  V_LISTAINI      NUMBER := NULL; -- ANDRE IMAKAWA - SIG 41089
  V_LISTACOUNT    NUMBER := 0;    -- ANDRE IMAKAWA - SIG 41089
  V_IDTITULAR_AUX NUMBER := 0;    -- ANDRE IMAKAWA - SIG 41089
  V_CONTROLE      NUMBER := 0;
  V_NOME_LISTA    VARCHAR2(50) := '_FBSP_MAQUINA_VIRTUAL_' || V_MES || '_' ||
                                  TO_CHAR(SYSDATE, 'DDMMYYYY_HH24MISS');
  --V_QTDMATLISTA   NUMBER := 0;    -- ANDRE IMAKAWA - SIG 41089
  --V_AUXILIAR      NUMBER := 1;    -- ANDRE IMAKAWA - SIG 41089

  CURSOR LISTAMATRICULAS IS
    SELECT HST.IDTITULAR, HST.IDPESSOA
      FROM HSTBENEFBFCIARIO HST,
           PESSOA           PES,
           PESSOAFISICA     PF,
           PATRO            PAT,
           BENEFPLANPREV    BPP,
           BENEFPLANPATRO   BPPAT,
           CTRLINTERFACE    CTL,
           BFCIARIOTITPLAN  BTP,
           TPPAGTOBENEFICIO TPB,
           BENEFBFCIARIO    BBF,
           PARTPREVPLAN     PP,
           ELEGPATRO        EL,
           PESSOA           PREC,
           PLANPREV         PL,
           BENEFPLANOPART   BPART,
           COMPENSAIRRF     CIRRF,
           ENDPESS          EN,
           CIDADES          CI,
           ESTADO           ES,
           PAIS             PA,
           PROCESSOBENEF    PROC,
           BENEFICIO        BEN
     WHERE (HST.FLGENVIADO = 0)
       AND ((HST.MESREFERENCIA <= V_MES) OR (HST.MESREFERENCIA = V_MES13))
       AND (HST.MES <= V_MES)
       AND (HST.DTEFETPGTO IS NULL)
       AND (HST.VLBENEFPGTO IS NULL)
       AND (HST.IDLOTE = CTL.IDLOTE)
       AND (HST.VALORPREV >= 0 OR NVL(BPP.FLGACEITAZERO, 0) = 1)
       AND (BEN.IDBENEFICIO = HST.IDBENEFICIO)
       AND (PL.IDPLANOPREV = HST.IDPLANOPREV)
       AND (BTP.IDPESSJUR = HST.IDPESSJUR)
       AND (BTP.IDPLANOPREV = HST.IDPLANOPREV)
       AND (BTP.IDPLANOORIGEM = HST.IDPLANOORIGEM)
       AND (BTP.IDPESSOA = HST.IDPESSOA)
       AND (BTP.SEQPROPOSTA = HST.SEQPROPOSTA)
       AND (BTP.IDTITULAR = HST.IDTITULAR)
       AND (BTP.IDBENEFICIO = HST.IDBENEFICIO)
       AND (BPART.IDPESSJUR(+) = HST.IDPESSJUR)
       AND (BPART.IDPLANOPREV(+) = HST.IDPLANOPREV)
       AND (BPART.IDPESSOA(+) = HST.IDPESSOA)
       AND (BPART.SEQPROPOSTA(+) = HST.SEQPROPOSTA)
       AND (BPART.IDBENEFICIO(+) = HST.IDBENEFICIO)
       AND (CIRRF.IDPESSOA(+) = BTP.IDRESPONSAVEL)
       AND (EN.IDPESSOA(+) = PREC.IDPESSOA)
       AND NVL(PREC.IDENDRESIDENCIAL, PREC.IDENDCORRESP) = EN.IDENDERECO(+)
       AND (CI.IDCIDADES(+) = EN.IDCIDADES)
       AND (ES.IDESTADO(+) = CI.IDESTADO)
       AND (PA.IDPAIS(+) = ES.IDPAIS)
       AND (BPP.IDPLANOPREV = HST.IDPLANOPREV)
       AND (BPP.IDBENEFICIO = HST.IDBENEFICIO)
       AND ((BPP.FLGREFERENCIA IS NULL) OR (BPP.FLGREFERENCIA = 0) OR
           ((BPP.FLGREFERENCIA = 1) AND (BPP.FLGPAGAINSS = 1)))
       AND (BBF.NUMEROPROCESSO = HST.NUMEROPROCESSO)
       AND (BBF.IDPESSOA = HST.IDPESSOA)
       AND (BBF.IDPESSJUR = HST.IDPESSJUR)
       AND (BBF.IDPLANOPREV = HST.IDPLANOPREV)
       AND (BBF.IDTITULAR = HST.IDTITULAR)
       AND (BBF.IDBENEFICIO = HST.IDBENEFICIO)
       AND (BBF.SEQPROPOSTA = HST.SEQPROPOSTA)
       AND (BBF.IDPLANOORIGEM = HST.IDPLANOORIGEM)
       AND (TPB.IDTPPAGTOBENEFIC = BBF.IDTPPAGTOBENEFIC)
       AND (PP.IDPESSOA = HST.IDTITULAR)
       AND (PP.IDPESSJUR = HST.IDPESSJUR)
       AND ((HST.IDPLANOPREV = PP.IDPLANOPREV AND
           HST.IDPESSOA = HST.IDTITULAR) OR
           (HST.IDPLANOORIGEM = PP.IDPLANOPREV AND
           HST.IDPESSOA <> HST.IDTITULAR))
       AND (EL.IDPESSOA = HST.IDTITULAR)
       AND (EL.IDPESSJUR = HST.IDPESSJUR)
       AND (PROC.NUMEROPROCESSO = HST.NUMEROPROCESSO)
       AND (BPPAT.IDPESSJUR(+) = HST.IDPESSJUR)
       AND (BPPAT.IDPLANOPREV(+) = HST.IDPLANOPREV)
       AND (BPPAT.IDBENEFICIO(+) = HST.IDBENEFICIO)
       AND (PF.IDPESSOA = BTP.IDRESPONSAVEL)
       AND (PREC.IDPESSOA = BTP.IDRESPONSAVEL)
       AND (PAT.IDPESSOA = HST.IDPESSJUR)
       AND (PAT.IDFUNDACAO = 1)
       AND (PES.IDPESSOA = HST.IDPESSOA)
     GROUP BY HST.IDTITULAR, HST.IDPESSOA
     ORDER BY HST.IDTITULAR, HST.IDPESSOA;

  CURSOR LISTAAUTORIZADOS IS --SPLIT DOS USRS PASSADOS POR ,
    SELECT TO_NUMBER(REGEXP_SUBSTR(LISTAUSR, '[^,]+', 1, ROWNUM)) IDUSUARIO
      FROM DUAL
    CONNECT BY LEVEL <= LENGTH(REGEXP_REPLACE(LISTAUSR, '[^,]+')) + 1;

BEGIN
  V_LISTAINI   := null; -- ANDRE IMAKAWA - SIG 41089
  V_LISTACOUNT := 0;    -- ANDRE IMAKAWA - SIG 41089
  SELECT COUNT(REGEXP_SUBSTR(LISTAUSR, '[^,]+', 1, ROWNUM)) IDUSUARIO
    INTO V_QTDPROCESSOS
    FROM DUAL
  CONNECT BY LEVEL <= LENGTH(REGEXP_REPLACE(LISTAUSR, '[^,]+')) + 1;

  SELECT COUNT(1)
    INTO V_QTDMATRICULAS
    FROM (SELECT 1
            FROM HSTBENEFBFCIARIO HST,
                 PESSOA           PES,
                 PESSOAFISICA     PF,
                 PATRO            PAT,
                 BENEFPLANPREV    BPP,
                 BENEFPLANPATRO   BPPAT,
                 CTRLINTERFACE    CTL,
                 BFCIARIOTITPLAN  BTP,
                 TPPAGTOBENEFICIO TPB,
                 BENEFBFCIARIO    BBF,
                 PARTPREVPLAN     PP,
                 ELEGPATRO        EL,
                 PESSOA           PREC,
                 PLANPREV         PL,
                 BENEFPLANOPART   BPART,
                 COMPENSAIRRF     CIRRF,
                 ENDPESS          EN,
                 CIDADES          CI,
                 ESTADO           ES,
                 PAIS             PA,
                 PROCESSOBENEF    PROC,
                 BENEFICIO        BEN
           WHERE (HST.FLGENVIADO = 0)
             AND ((HST.MESREFERENCIA <= V_MES) OR
                 (HST.MESREFERENCIA = V_MES13))
             AND (HST.MES <= V_MES)
             AND (HST.DTEFETPGTO IS NULL)
             AND (HST.VLBENEFPGTO IS NULL)
             AND (HST.IDLOTE = CTL.IDLOTE)
             AND (HST.VALORPREV >= 0 OR NVL(BPP.FLGACEITAZERO, 0) = 1)
             AND (BEN.IDBENEFICIO = HST.IDBENEFICIO)
             AND (PL.IDPLANOPREV = HST.IDPLANOPREV)
             AND (BTP.IDPESSJUR = HST.IDPESSJUR)
             AND (BTP.IDPLANOPREV = HST.IDPLANOPREV)
             AND (BTP.IDPLANOORIGEM = HST.IDPLANOORIGEM)
             AND (BTP.IDPESSOA = HST.IDPESSOA)
             AND (BTP.SEQPROPOSTA = HST.SEQPROPOSTA)
             AND (BTP.IDTITULAR = HST.IDTITULAR)
             AND (BTP.IDBENEFICIO = HST.IDBENEFICIO)
             AND (BPART.IDPESSJUR(+) = HST.IDPESSJUR)
             AND (BPART.IDPLANOPREV(+) = HST.IDPLANOPREV)
             AND (BPART.IDPESSOA(+) = HST.IDPESSOA)
             AND (BPART.SEQPROPOSTA(+) = HST.SEQPROPOSTA)
             AND (BPART.IDBENEFICIO(+) = HST.IDBENEFICIO)
             AND (CIRRF.IDPESSOA(+) = BTP.IDRESPONSAVEL)
             AND (EN.IDPESSOA(+) = PREC.IDPESSOA)
             AND NVL(PREC.IDENDRESIDENCIAL, PREC.IDENDCORRESP) =
                 EN.IDENDERECO(+)
             AND (CI.IDCIDADES(+) = EN.IDCIDADES)
             AND (ES.IDESTADO(+) = CI.IDESTADO)
             AND (PA.IDPAIS(+) = ES.IDPAIS)
             AND (BPP.IDPLANOPREV = HST.IDPLANOPREV)
             AND (BPP.IDBENEFICIO = HST.IDBENEFICIO)
             AND ((BPP.FLGREFERENCIA IS NULL) OR (BPP.FLGREFERENCIA = 0) OR
                 ((BPP.FLGREFERENCIA = 1) AND (BPP.FLGPAGAINSS = 1)))
             AND (BBF.NUMEROPROCESSO = HST.NUMEROPROCESSO)
             AND (BBF.IDPESSOA = HST.IDPESSOA)
             AND (BBF.IDPESSJUR = HST.IDPESSJUR)
             AND (BBF.IDPLANOPREV = HST.IDPLANOPREV)
             AND (BBF.IDTITULAR = HST.IDTITULAR)
             AND (BBF.IDBENEFICIO = HST.IDBENEFICIO)
             AND (BBF.SEQPROPOSTA = HST.SEQPROPOSTA)
             AND (BBF.IDPLANOORIGEM = HST.IDPLANOORIGEM)
             AND (TPB.IDTPPAGTOBENEFIC = BBF.IDTPPAGTOBENEFIC)
             AND (PP.IDPESSOA = HST.IDTITULAR)
             AND (PP.IDPESSJUR = HST.IDPESSJUR)
             AND ((HST.IDPLANOPREV = PP.IDPLANOPREV AND
                 HST.IDPESSOA = HST.IDTITULAR) OR
                 (HST.IDPLANOORIGEM = PP.IDPLANOPREV AND
                 HST.IDPESSOA <> HST.IDTITULAR))
             AND (EL.IDPESSOA = HST.IDTITULAR)
             AND (EL.IDPESSJUR = HST.IDPESSJUR)
             AND (PROC.NUMEROPROCESSO = HST.NUMEROPROCESSO)
             AND (BPPAT.IDPESSJUR(+) = HST.IDPESSJUR)
             AND (BPPAT.IDPLANOPREV(+) = HST.IDPLANOPREV)
             AND (BPPAT.IDBENEFICIO(+) = HST.IDBENEFICIO)
             AND (PF.IDPESSOA = BTP.IDRESPONSAVEL)
             AND (PREC.IDPESSOA = BTP.IDRESPONSAVEL)
             AND (PAT.IDPESSOA = HST.IDPESSJUR)
             AND (PAT.IDFUNDACAO = 1)
             AND (PES.IDPESSOA = HST.IDPESSOA)
           GROUP BY HST.IDTITULAR, HST.IDPESSOA);

  IF V_QTDMATRICULAS > 0 THEN
  
    --V_QTDMATLISTA := TRUNC(V_QTDMATRICULAS / V_QTDPROCESSOS) + 1; -- ANDRE IMAKAWA - SIG 41089
  
    LOOP
      V_CONTROLE := V_CONTROLE + 1;
    
      SELECT CM.SEQLISTAFOLHABENEF.NEXTVAL INTO V_LISTA FROM DUAL;
    
      -- ANDRE IMAKAWA - SIG 41089 - INICIO   
      IF V_LISTAINI IS NULL then
        V_LISTAINI := V_LISTA;
      End if;
      -- ANDRE IMAKAWA - SIG 41089 - FIM
      
      INSERT INTO CM.LISTAFOLHABENEF
        (IDLISTA, FLGTIPOLISTA, NOME)
      VALUES
        (V_LISTA, 1, V_CONTROLE || V_NOME_LISTA);
    
      EXIT WHEN V_CONTROLE = V_QTDPROCESSOS;
    
    END LOOP;
  
    COMMIT;
  
    FOR ITEMLISTAAUTORIZADOS IN LISTAAUTORIZADOS LOOP
    
      UPDATE CM.LISTAFOLHABENEF
         SET IDUSUARIO = NULL
       WHERE IDUSUARIO = ITEMLISTAAUTORIZADOS.IDUSUARIO;
    
      UPDATE CM.LISTAFOLHABENEF
         SET IDUSUARIO = ITEMLISTAAUTORIZADOS.IDUSUARIO
       WHERE IDLISTA = V_LISTA
         AND NOME = V_CONTROLE || V_NOME_LISTA;
    
      V_LISTA    := V_LISTA - 1;
      V_CONTROLE := V_CONTROLE - 1;
    
    END LOOP;
  
    COMMIT;
  
    V_LISTA    := V_LISTA + 1;
    V_CONTROLE := 0;
  
    FOR ITEMLISTAMATRICULAS IN LISTAMATRICULAS LOOP
    
    -- ANDRE IMAKAWA - SIG 41089 - INICIO
    /*
      V_CONTROLE := V_CONTROLE + 1;
    
      IF ((V_CONTROLE >= V_QTDMATLISTA * V_AUXILIAR) AND
         (ITEMLISTAMATRICULAS.IDPESSOA = ITEMLISTAMATRICULAS.IDTITULAR)) THEN
      
        V_AUXILIAR := V_AUXILIAR + 1;
      
        V_LISTA := V_LISTA + 1;
      
        COMMIT;
      
      END IF;
     */
     
      IF V_IDTITULAR_AUX = 0 OR
         V_IDTITULAR_AUX <> ITEMLISTAMATRICULAS.IDTITULAR THEN
         
        V_LISTACOUNT := V_LISTACOUNT + 1; 
        
        IF V_LISTACOUNT > V_QTDPROCESSOS THEN
          V_LISTA      := V_LISTAINI;
          V_LISTACOUNT := 1;
        ELSIF V_LISTACOUNT = 1 THEN
          V_LISTA := V_LISTAINI;
        ELSE
          V_LISTA := V_LISTA + 1;
        END IF;
      End If;
      -- ANDRE IMAKAWA - SIG 41089 - FIM
      
      INSERT INTO CM.LISTAFOLHABENEFDET
        (IDLISTA, IDTITULAR, IDPESSOA, IDREFERENCIA)
      VALUES
        (V_LISTA,
         ITEMLISTAMATRICULAS.IDTITULAR,
         ITEMLISTAMATRICULAS.IDPESSOA,
         ITEMLISTAMATRICULAS.IDPESSOA);
    
      IF V_CONTROLE MOD 1000 = 0 THEN
        COMMIT;
      END IF;
    
      V_IDTITULAR_AUX := ITEMLISTAMATRICULAS.IDTITULAR; -- ANDRE IMAKAWA - SIG 41089
    
    END LOOP;
  
    COMMIT;
  
  END IF;

  COMMIT;

END SP_FB_GERALISTAPREVIA;
