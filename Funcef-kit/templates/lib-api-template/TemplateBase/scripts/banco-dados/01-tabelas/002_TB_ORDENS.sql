CREATE TABLE TEMPLATETESTE.TB_ORDENS (
    ORDEM_ID                NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CLIENTE_ID              NUMBER NOT NULL,
    VALOR                   NUMBER(10,2) NOT NULL,
    STATUS                  VARCHAR2(20 CHAR) DEFAULT 'Pendente' NOT NULL,
    OBSERVACOES             VARCHAR2(500 CHAR),
    DATA_PEDIDO             DATE DEFAULT SYSDATE NOT NULL,
    DATA_INCLUSAO_ALTERACAO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_ORDENS
        PRIMARY KEY (ORDEM_ID),

    CONSTRAINT FK_ORDENS_CLIENTES
        FOREIGN KEY (CLIENTE_ID)
        REFERENCES TEMPLATETESTE.TB_CLIENTES (CLIENTE_ID),

    CONSTRAINT CK_ORDENS_STATUS
        CHECK (STATUS IN ('Pendente','Processando','Enviado','Concluido','Cancelado')),

    CONSTRAINT CK_ORDENS_VALOR
        CHECK (VALOR > 0)
);

-- Comentários
COMMENT ON TABLE TEMPLATETESTE.TB_ORDENS IS
'Ordens/pedidos de compra vinculados a clientes. Granularidade: 1 linha = 1 ordem.';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.ORDEM_ID IS
'Identificador técnico (PK)';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.CLIENTE_ID IS
'Cliente que realizou o pedido (FK para TB_CLIENTES)';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.VALOR IS
'Valor monetário total da ordem (positivo, 8 inteiros e 2 decimais)';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.STATUS IS
'Situação da ordem (Pendente, Processando, Enviado, Concluido, Cancelado)';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.OBSERVACOES IS
'Texto livre para anotações e instruções especiais do pedido';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.DATA_PEDIDO IS
'Data em que o pedido foi registrado no sistema';

COMMENT ON COLUMN TEMPLATETESTE.TB_ORDENS.DATA_INCLUSAO_ALTERACAO IS
'Data de inclusão/alteração — controle de carga incremental';
