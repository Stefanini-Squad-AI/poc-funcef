CREATE TABLE TEMPLATETESTE.TB_CLIENTES (
    CLIENTE_ID              NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME                    VARCHAR2(100 CHAR) NOT NULL,
    EMAIL                   VARCHAR2(150 CHAR),
    DATA_CRIACAO            DATE DEFAULT SYSDATE NOT NULL,
    DATA_INCLUSAO_ALTERACAO DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_CLIENTES
        PRIMARY KEY (CLIENTE_ID),

    CONSTRAINT UK_CLIENTES_EMAIL
        UNIQUE (EMAIL)
);

-- Comentários
COMMENT ON TABLE TEMPLATETESTE.TB_CLIENTES IS
'Cadastro de clientes do domínio de exemplo do template. Granularidade: 1 linha = 1 cliente.';

COMMENT ON COLUMN TEMPLATETESTE.TB_CLIENTES.CLIENTE_ID IS
'Identificador técnico (PK)';

COMMENT ON COLUMN TEMPLATETESTE.TB_CLIENTES.NOME IS
'Nome completo ou razão social do cliente';

COMMENT ON COLUMN TEMPLATETESTE.TB_CLIENTES.EMAIL IS
'Endereço de e-mail para contato (único quando informado)';

COMMENT ON COLUMN TEMPLATETESTE.TB_CLIENTES.DATA_CRIACAO IS
'Data em que o cliente foi cadastrado no sistema';

COMMENT ON COLUMN TEMPLATETESTE.TB_CLIENTES.DATA_INCLUSAO_ALTERACAO IS
'Data de inclusão/alteração — controle de carga incremental';
